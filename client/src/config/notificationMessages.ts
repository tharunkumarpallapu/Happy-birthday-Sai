/**
 * Get a random message from an array
 */
export function getRandomMessage(messages: string[]): string {
  return messages[Math.floor(Math.random() * messages.length)];
}

/**
 * Get a random message excluding the last one (to avoid repetition)
 */
export function getRandomMessageExcluding(messages: string[], exclude: string): string {
  let message = getRandomMessage(messages);
  while (message === exclude && messages.length > 1) {
    message = getRandomMessage(messages);
  }
  return message;
}

